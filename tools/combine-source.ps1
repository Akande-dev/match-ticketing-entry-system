# Builds docs/SOURCE_CODE_ALL.txt: every source file in one readable listing.
# The real project keeps separate files (Node backend, Vite web app, tests).
# Run: powershell -NoProfile -ExecutionPolicy Bypass -File tools\combine-source.ps1
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root
$files = @(Get-Item functions\index.js, firestore.rules, web\index.html)
$files += Get-ChildItem functions\src, functions\scripts, functions\test, web\src -Recurse -File |
  Where-Object { $_.Extension -in '.js', '.jsx', '.css' } | Sort-Object FullName
$rel = { param($f) $f.FullName.Substring($root.Length + 1) }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('MATCH TICKETING AND STADIUM ENTRY SYSTEM - combined source listing')
[void]$sb.AppendLine('Generated: ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
[void]$sb.AppendLine('Generated by tools/combine-source.ps1. The project itself keeps separate files. Do not edit this listing.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('CONTENTS')
$total = 0
foreach ($f in $files) {
  $n = @(Get-Content $f.FullName).Count
  $total += $n
  [void]$sb.AppendLine(('{0,5} lines  {1}' -f $n, (& $rel $f)))
}
[void]$sb.AppendLine(('{0,5} lines  TOTAL in {1} files' -f $total, $files.Count))
foreach ($f in $files) {
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine('=' * 78)
  [void]$sb.AppendLine('FILE: ' + (& $rel $f))
  [void]$sb.AppendLine('=' * 78)
  [void]$sb.AppendLine(((Get-Content $f.FullName -Raw) -replace "`r`n", "`n").TrimEnd("`n"))
}
[IO.File]::WriteAllText((Join-Path $root 'docs\SOURCE_CODE_ALL.txt'), $sb.ToString(), (New-Object Text.UTF8Encoding $false))
"Wrote docs\SOURCE_CODE_ALL.txt : $($files.Count) files, $total lines"
